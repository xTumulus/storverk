const ROOT = resolve(import.meta.dirname, "..");
const CONTENT_DIR = join(ROOT, "content");
const OUT_DIR = join(ROOT, "src/generated");
const README_CACHE_FILE = join(CONTENT_DIR, ".cache/github-readmes.json");

// `Input = any` (rather than the default `Input = Output`) so T is inferred
// purely from the schema's output side — otherwise fields with `.default()`
// (whose input type is optional) pollute inference and T comes out with
// those fields optional too, even though the parsed output always has them.
/** Required content files must exist — this is the one message users see when they don't. */
function requireContentFile(relativePath: string): string {
  const fullPath = join(CONTENT_DIR, relativePath);
  if (!existsSync(fullPath)) {
    throw new Error(
      `You are missing a file: ${relativePath}. Add ${basename(relativePath)} at this location with the same format as the example file found in the repository`,
    );
  }
  return fullPath;
}

function readYamlFile<T>(
  relativePath: string,
  // eslint-disable-next-line @typescript-eslint/no-explicit-any -- see comment above: Input is intentionally untyped
  schema: z.ZodType<T, z.ZodTypeDef, any>,
): T {
  const fullPath = requireContentFile(relativePath);
  const raw = parseYaml(readFileSync(fullPath, "utf-8"));
  const result = schema.safeParse(raw);
  if (!result.success) {
    throw new Error(
      `Invalid content in ${relativePath}:\n${result.error.issues
        .map((issue) => `  - ${issue.path.join(".")}: ${issue.message}`)
        .join("\n")}`,
    );
  }
  return result.data;
}

function readMarkdownFile(fullPath: string) {
  return matter(readFileSync(fullPath, "utf-8"));
}

/** Like readMarkdownFile, but for required top-level files (not ones already discovered via readdirSync). */
function readRequiredMarkdownFile(relativePath: string) {
  return readMarkdownFile(requireContentFile(relativePath));
}

function writeGenerated(filename: string, banner: string, body: string) {
  writeFileSync(join(OUT_DIR, filename), `${banner}\n\n${body}\n`);
}

const GENERATED_BANNER =
  "// AUTO-GENERATED by scripts/build-content.ts — do not edit directly.\n// Edit the corresponding file(s) under content/ instead, then rebuild.";

function buildSiteConfig() {
  const config = readYamlFile("site.config.yaml", siteConfigSchema);
  writeGenerated(
    "site-config.ts",
    GENERATED_BANNER,
    `import type { SiteConfig } from '../../schemas/site-config.ts'\n\nexport const siteConfig: SiteConfig = ${JSON.stringify(config, null, 2)}\n`,
  );
}

function buildAbout() {
  const summaryFile = readRequiredMarkdownFile("about/summary.md");
  const summary: Summary = {
    name: String(summaryFile.data.name ?? ""),
    title: String(summaryFile.data.title ?? ""),
    bodyHtml: md.render(summaryFile.content),
  };

  const skills = readYamlFile("about/skills.yaml", skillsSchema);
  const education = readYamlFile("about/education.yaml", educationSchema);
  const experience = readYamlFile("about/experience.yaml", experienceSchema);
  const credentials = readYamlFile("about/credentials.yaml", credentialsSchema);
  const volunteer = readYamlFile("about/volunteer.yaml", volunteerSchema);
  const languages = readYamlFile("about/languages.yaml", languagesSchema);

  writeGenerated(
    "about.ts",
    GENERATED_BANNER,
    [
      `import type { Summary } from '../../schemas/summary.ts'`,
      `import type { Skill } from '../../schemas/skill.ts'`,
      `import type { EducationEntry } from '../../schemas/education.ts'`,
      `import type { ExperienceEntry } from '../../schemas/experience.ts'`,
      `import type { CredentialEntry } from '../../schemas/credentials.ts'`,
      `import type { VolunteerEntry } from '../../schemas/volunteer.ts'`,
      `import type { LanguageEntry } from '../../schemas/language.ts'`,
      "",
      `export const summary: Summary = ${JSON.stringify(summary, null, 2)}`,
      `export const skills: Skill[] = ${JSON.stringify(skills, null, 2)}`,
      `export const education: EducationEntry[] = ${JSON.stringify(education, null, 2)}`,
      `export const experience: ExperienceEntry[] = ${JSON.stringify(experience, null, 2)}`,
      `export const credentials: CredentialEntry[] = ${JSON.stringify(credentials, null, 2)}`,
      `export const volunteer: VolunteerEntry[] = ${JSON.stringify(volunteer, null, 2)}`,
      `export const languages: LanguageEntry[] = ${JSON.stringify(languages, null, 2)}`,
    ].join("\n\n"),
  );
}

function buildHomeLanding() {
  const homeFile = readRequiredMarkdownFile("home.md");
  const result = homeSchema.safeParse(homeFile.data);
  if (!result.success) {
    throw new Error(
      `Invalid frontmatter in home.md:\n${result.error.issues
        .map((issue) => `  - ${issue.path.join(".")}: ${issue.message}`)
        .join("\n")}`,
    );
  }
  const home: Home = {
    ...result.data,
    bodyHtml: md.render(homeFile.content),
  };

  writeGenerated(
    "home.ts",
    GENERATED_BANNER,
    `import type { Home } from '../../schemas/home.ts'\n\nexport const home: Home = ${JSON.stringify(home, null, 2)}\n`,
  );
}

