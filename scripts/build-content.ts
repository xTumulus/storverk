function buildHobbies() {
  const hobbyEntries = readYamlFile("hobbies/hobbies.yaml", hobbiesSchema);
  const hobbiesDir = join(CONTENT_DIR, "hobbies");

  const hobbies: Hobby[] = hobbyEntries.map((hobby) => {
    const bodyFile = join(hobbiesDir, `${hobby.id}.md`);
    const bodyHtml = existsSync(bodyFile)
      ? md.render(readMarkdownFile(bodyFile).content)
      : null;
    return { ...hobby, bodyHtml };
  });

  writeGenerated(
    "hobbies.ts",
    GENERATED_BANNER,
    `import type { Hobby } from '../../schemas/hobby.ts'\n\nexport const hobbies: Hobby[] = ${JSON.stringify(hobbies, null, 2)}\n`,
  );
}

function main() {
  rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });

  buildSiteConfig();
  buildAbout();
  buildHomeLanding();
  buildContact();
  buildProjects();
  buildLinks();
  buildSocial();
  buildHobbies();

  console.log("Content pipeline: generated src/generated/*.ts from content/");
}

try {
  main();
} catch (err) {
  // Thrown as a plain Error with a message already formatted for humans
  // (see readYamlFile / readMarkdownFile above) — print just that instead
  // of letting Node dump the raw stack trace, so the reason a content edit
  // failed to publish is the first thing visible in watch-content.ts's log
  // output rather than being buried under internal frames.
  console.error(`Content pipeline failed:\n${err instanceof Error ? err.message : err}`);
  process.exit(1);
}
