/** Parses every devlog file under `content/projects/devlogs/<slug>/`, newest first. */
function readDevlogs(slug: string): DevlogEntry[] {
  const dir = join(CONTENT_DIR, "projects/devlogs", slug);
  const files = existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".md"))
    : [];

  const entries: DevlogEntry[] = files.map((file) => {
    // Filenames are date-prefixed, e.g. 2026-02-10-update-title.md
    const dateMatch = file.match(/^(\d{4}-\d{2}-\d{2})-/);
    if (!dateMatch) {
      throw new Error(
        `Devlog file ${slug}/${file} must be named YYYY-MM-DD-<slug>.md`,
      );
    }
    const { data, content } = readMarkdownFile(join(dir, file));
    const result = devlogFrontmatterSchema.safeParse(data);
    if (!result.success) {
      throw new Error(
        `Invalid frontmatter in projects/devlogs/${slug}/${file}:\n${result.error.issues
          .map((issue) => `  - ${issue.path.join(".")}: ${issue.message}`)
          .join("\n")}`,
      );
    }
    const plainText = content.replace(/[#*_`>[\]()]/g, "").trim();
    return {
      ...result.data,
      date: dateMatch[1],
      bodyHtml: md.render(content),
      excerpt:
        plainText.length > 160 ? `${plainText.slice(0, 160)}…` : plainText,
      videoId: result.data.video ? parseYoutubeId(result.data.video) : null,
    };
  });

  entries.sort((a, b) => (a.date < b.date ? 1 : -1)); // newest first
  return entries;
}

function buildProjects() {
  const dir = join(CONTENT_DIR, "projects");
  const files = existsSync(dir)
    ? readdirSync(dir).filter((f) => f.endsWith(".md"))
    : [];

  let readmeCache: Record<
    string,
    { description: string; htmlUrl: string; stars: number; readmeHtml: string }
  > = {};
  if (existsSync(README_CACHE_FILE)) {
    readmeCache = JSON.parse(readFileSync(README_CACHE_FILE, "utf-8"));
  }

  const devlogsBySlug: Record<string, DevlogEntry[]> = {};

  const projects: Project[] = files.map((file) => {
    const slug = file.replace(/\.md$/, "");
    const { data, content } = readMarkdownFile(join(dir, file));
    const result = projectFrontmatterSchema.safeParse(data);
    if (!result.success) {
      throw new Error(
        `Invalid frontmatter in projects/${file}:\n${result.error.issues
          .map((issue) => `  - ${issue.path.join(".")}: ${issue.message}`)
          .join("\n")}`,
      );
    }
    const frontmatter = result.data;

    let bodyHtml: string;
    let stars: number | null;
    let repoUrl = frontmatter.repoUrl;
    if (frontmatter.repo) {
      const key = `${frontmatter.repo.owner}/${frontmatter.repo.repo}`;
      const cached = readmeCache[key];
      if (!cached && process.env.NODE_ENV !== "test") {
        console.warn(
          `No cached data for ${key} — run "npm run fetch:github" before building. Using placeholder.`,
        );
      }
      bodyHtml =
        cached?.readmeHtml ??
        "<p><em>README unavailable — run npm run fetch:github.</em></p>";
      stars = cached?.stars ?? 0;
      repoUrl = cached?.htmlUrl ?? `https://github.com/${key}`;
    } else {
      bodyHtml = md.render(content);
      stars = null;
    }

    const devlogs = readDevlogs(slug);
    devlogsBySlug[slug] = devlogs;

    return {
      ...frontmatter,
      slug,
      bodyHtml,
      stars,
      repoUrl,
      videoId: frontmatter.videoUrl ? parseYoutubeId(frontmatter.videoUrl) : null,
      latestDevlog: devlogs[0] ?? null,
    };
  });

  projects.sort((a, b) => a.order - b.order);

  writeGenerated(
    "projects.ts",
    GENERATED_BANNER,
    `import type { Project } from '../../schemas/project.ts'\n\nexport const projects: Project[] = ${JSON.stringify(projects, null, 2)}\n`,
  );

  writeGenerated(
    "devlogs.ts",
    GENERATED_BANNER,
    `import type { DevlogEntry } from '../../schemas/devlog.ts'\n\nexport const devlogsBySlug: Record<string, DevlogEntry[]> = ${JSON.stringify(devlogsBySlug, null, 2)}\n`,
  );
}

